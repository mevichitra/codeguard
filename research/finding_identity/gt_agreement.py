"""Score the manual ground-truth check: how often the harness's truth holds, per rater,
and how well two raters agree.

``python -m research.finding_identity.gt_agreement --human <labels> --agent <labels>``
reads the key (``sample.csv`` from :mod:`gt_sample`) and each rater's labels, keyed by
the blinded item id, and writes ``agreement.md`` next to the key.

Labels: a JSON object ``{item: {"verdict": ...}}``, or a directory of ``<item>.json``
files (as the labelling page's store exports them). A ``pair`` verdict of ``same`` and an
``introduced`` verdict of ``new`` confirm the harness's truth; ``different`` and
``existed`` contradict it; ``unclear`` counts for neither.

``--adjudicated`` adds the final verdict per item (same format, each with a ``source``
saying who settled it). With ``--results`` (the corpus replays the sample came from),
the report also estimates each content scheme's hidden rate after removing the
ground-truth errors: every hidden finding of those schemes lies in the
``new_but_matched`` stratum, so its count is scaled by the share of that scheme's
sampled matches that the adjudication confirms as truly new. The replays may use a
newer ground truth than the one the sample was drawn from: each sampled finding is then
looked up in them, the scaling uses only the sampled findings they still count as
introduced and hidden, and the report says how often their ground truth agrees with
the adjudicated verdicts.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from collections.abc import Mapping, Sequence
from pathlib import Path

from .gt_sample import CONTENT_SCHEMES
from .stats import wilson

HERE = Path(__file__).parent
KEY = HERE / "paper" / "ground_truth_check" / "sample.csv"

CONFIRMS = {"same", "new"}
CONTRADICTS = {"different", "existed"}


def load_labels(path: Path) -> dict[str, str]:
    """``{item: verdict}`` from a JSON file or a directory of per-item JSON files."""
    if path.is_dir():
        out = {}
        for f in sorted(path.rglob("*.json")):
            body = json.loads(f.read_text(encoding="utf-8"))
            body = body.get("data", body) if isinstance(body, dict) else {}
            if isinstance(body, dict) and isinstance(body.get("verdict"), str):
                out[f.stem] = body["verdict"]
        return out
    raw = json.loads(path.read_text(encoding="utf-8"))
    return {k: v["verdict"] for k, v in raw.items() if isinstance(v, dict) and "verdict" in v}


def judgement(verdict: str | None) -> str:
    """``confirms``, ``contradicts`` or ``unclear`` (also for a missing label)."""
    if verdict in CONFIRMS:
        return "confirms"
    if verdict in CONTRADICTS:
        return "contradicts"
    return "unclear"


def cohen_kappa(a: Sequence[str], b: Sequence[str]) -> float | None:
    """Cohen's kappa for two equally long label sequences; ``None`` if undefined."""
    n = len(a)
    if n == 0 or n != len(b):
        return None
    observed = sum(x == y for x, y in zip(a, b, strict=True)) / n
    ca, cb = Counter(a), Counter(b)
    expected = sum(ca[k] * cb[k] for k in ca.keys() | cb.keys()) / (n * n)
    if expected == 1:
        return None
    return (observed - expected) / (1 - expected)


def precision_rows(
    key: Sequence[Mapping[str, str]], labels: Mapping[str, str], group: str
) -> list[tuple[str, int, int, int]]:
    """Per value of *group* (and overall): (name, confirms, contradicts, unclear)."""
    groups: dict[str, Counter[str]] = {}
    for row in key:
        j = judgement(labels.get(row["item"]))
        for name in (row[group], "all"):
            groups.setdefault(name, Counter())[j] += 1
    names = [*sorted(n for n in groups if n != "all"), "all"]
    return [
        (n, groups[n]["confirms"], groups[n]["contradicts"], groups[n]["unclear"]) for n in names
    ]


def _kind(row: Mapping[str, str]) -> str:
    return "introduced" if row["truth"] == "new" else "pair"


def report(
    key: Sequence[Mapping[str, str]],
    raters: Mapping[str, Mapping[str, str]],
    *,
    header: bool = True,
) -> str:
    rows = [{**r, "kind": _kind(r)} for r in key]
    out = (
        [
            "# Ground-truth check: results",
            "",
            "Generated by `research/finding_identity/gt_agreement.py`. *Holds* is the share of",
            "decided items (unclear left out) where the rater confirms the harness's truth, with",
            "a Wilson 95% interval.",
            "",
        ]
        if header
        else []
    )
    for name, labels in raters.items():
        labelled = sum(1 for r in rows if r["item"] in labels)
        out += [f"## {name}", "", f"{labelled} of {len(rows)} items labelled.", ""]
        for group in ("kind", "stratum"):
            out += [
                f"| {group} | confirms | contradicts | unclear | holds | 95% CI |",
                "|---|---:|---:|---:|---:|---|",
            ]
            for g, yes, no, unclear in precision_rows(rows, labels, group):
                ci = wilson(yes, yes + no)
                rate = f"{100 * yes / (yes + no):.1f}%" if yes + no else "n/a"
                cis = f"[{100 * ci[0]:.1f}, {100 * ci[1]:.1f}]" if ci else "n/a"
                out.append(f"| {g} | {yes} | {no} | {unclear} | {rate} | {cis} |")
            out.append("")
    names = list(raters)
    if len(names) == 2:
        both = [r for r in rows if r["item"] in raters[names[0]] and r["item"] in raters[names[1]]]
        a = [judgement(raters[names[0]][r["item"]]) for r in both]
        b = [judgement(raters[names[1]][r["item"]]) for r in both]
        kappa = cohen_kappa(a, b)
        agree = sum(x == y for x, y in zip(a, b, strict=True))
        out += [
            f"## Agreement between {names[0]} and {names[1]}",
            "",
            f"On the {len(both)} items both labelled (confirms / contradicts / unclear):",
            f"{agree} agree ({100 * agree / len(both):.1f}%), Cohen's kappa "
            + (f"{kappa:.2f}." if kappa is not None else "undefined.")
            if both
            else "No item is labelled by both.",
            "",
        ]
        disputed = [r["item"] for r, x, y in zip(both, a, b, strict=True) if x != y]
        if disputed:
            out += ["Items to adjudicate: " + ", ".join(disputed) + ".", ""]
    return "\n".join(out)


def _item_id(repository: str, rec: Mapping[str, object]) -> tuple[str, str, str, str, str]:
    return (
        repository,
        str(rec.get("commit")),
        str(rec.get("path")),
        str(rec.get("rule")),
        str(rec.get("line")),
    )


def sampled_records(
    key: Sequence[Mapping[str, str]], results: Path
) -> tuple[dict[str, dict[str, object]], Counter[str], int]:
    """The replay's record of each sampled finding (by item), plus each content scheme's
    hidden count and the number of introduced findings in the replay."""
    wanted = {
        _item_id(r.get("repository", ""), {**r, "line": r.get("line")}): r["item"] for r in key
    }
    found: dict[str, dict[str, object]] = {}
    hidden: Counter[str] = Counter()
    introduced = 0
    for f in sorted(results.glob("*/findings.jsonl")):
        with f.open(encoding="utf-8") as fh:
            for line in fh:
                rec = json.loads(line)
                item = wanted.get(_item_id(f.parent.name, rec))
                if item is not None:
                    found[item] = rec
                if rec["truth"] != "new":
                    continue
                introduced += 1
                for scheme in CONTENT_SCHEMES:
                    hidden[scheme] += rec["outcomes"][scheme] == "false_known"
    return found, hidden, introduced


def truth_holds(row: Mapping[str, str], verdict: str | None, rec: Mapping[str, object]) -> bool:
    """Whether a replay's ground truth for a sampled finding agrees with its verdict."""
    paired = rec["truth"] == "known" and str(rec.get("old_line")) == row["old_line"]
    if verdict == "same":
        return paired
    if verdict == "different":
        return not paired
    if verdict == "new":
        return rec["truth"] == "new"
    return rec["truth"] == "known"  # existed


def truth_agreement(
    key: Sequence[Mapping[str, str]], adjudicated: Mapping[str, str], results: Path
) -> list[str]:
    """Markdown lines: how often the replay's ground truth agrees with the verdicts."""
    found, _, _ = sampled_records(key, results)
    out = [
        "## Ground truth of the replays against the adjudicated verdicts",
        "",
        f"From `{results}`: {len(found)} of {len(key)} sampled findings found. *Holds*: the",
        "replay's ground truth agrees with the final verdict (Wilson 95% interval).",
        "",
    ]
    for group in ("kind", "stratum"):
        tally: dict[str, Counter[str]] = {}
        for row in key:
            rec = found.get(row["item"])
            verdict = adjudicated.get(row["item"])
            if rec is None or judgement(verdict) == "unclear":
                outcome = "undecided"
            else:
                outcome = "holds" if truth_holds(row, verdict, rec) else "fails"
            name = _kind(row) if group == "kind" else row["stratum"]
            for g in (name, "all"):
                tally.setdefault(g, Counter())[outcome] += 1
        out += [
            f"| {group} | holds | fails | undecided | holds | 95% CI |",
            "|---|---:|---:|---:|---:|---|",
        ]
        for g in [*sorted(n for n in tally if n != "all"), "all"]:
            yes, no, und = tally[g]["holds"], tally[g]["fails"], tally[g]["undecided"]
            ci = wilson(yes, yes + no)
            rate = f"{100 * yes / (yes + no):.1f}%" if yes + no else "n/a"
            cis = f"[{100 * ci[0]:.1f}, {100 * ci[1]:.1f}]" if ci else "n/a"
            out.append(f"| {g} | {yes} | {no} | {und} | {rate} | {cis} |")
        out.append("")
    return out


def corrected_hidden(
    key: Sequence[Mapping[str, str]], adjudicated: Mapping[str, str], results: Path
) -> list[str]:
    """Markdown lines: each content scheme's hidden rate before and after correction."""
    found, hidden, introduced = sampled_records(key, results)
    sample = [r for r in key if r["stratum"] == "new_but_matched"]
    out = [
        "## Hidden rates after correcting the ground truth",
        "",
        f"From `{results}`: {introduced:,} introduced findings. *Matched, sampled*: the",
        "scheme's hidden findings among the sampled `new_but_matched` items; *truly new*:",
        "those the adjudication confirms as new. The corrected rate scales the hidden",
        "count by that share (range: its Wilson 95% interval).",
        "",
        "| scheme | hidden | matched, sampled | truly new | corrected hidden | range |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for scheme in CONTENT_SCHEMES:

        def still_hidden(r: Mapping[str, str], scheme: str = scheme) -> bool:
            rec = found.get(r["item"])
            if rec is None:  # not in these replays: trust the sample
                return scheme in r["disagreeing_schemes"].split()
            outcomes = rec["outcomes"]
            assert isinstance(outcomes, dict)
            return rec["truth"] == "new" and outcomes[scheme] == "false_known"

        rows = [r for r in sample if still_hidden(r)]
        new = sum(judgement(adjudicated.get(r["item"])) == "confirms" for r in rows)
        ci = wilson(new, len(rows))
        rate = hidden[scheme] / introduced if introduced else 0.0
        if not rows or ci is None:
            out.append(f"| `{scheme}` | {100 * rate:.2f}% | 0 | 0 | n/a | n/a |")
            continue
        corrected = rate * new / len(rows)
        out.append(
            f"| `{scheme}` | {100 * rate:.2f}% ({hidden[scheme]}) | {len(rows)} | {new} | "
            f"{100 * corrected:.2f}% | [{100 * rate * ci[0]:.2f}, {100 * rate * ci[1]:.2f}] |"
        )
    return [*out, ""]


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="python -m research.finding_identity.gt_agreement")
    ap.add_argument("--key", type=Path, default=KEY, help="sample.csv from gt_sample")
    ap.add_argument("--human", type=Path, help="the person's labels (file or directory)")
    ap.add_argument(
        "--agent",
        type=Path,
        action="append",
        help="the agent rater's labels (file or directory); repeat it, and later files "
        "override earlier ones, item by item",
    )
    ap.add_argument(
        "--human-kind",
        choices=["pair", "introduced"],
        help="score only the person's labels of this item kind",
    )
    ap.add_argument("--adjudicated", type=Path, help="final verdicts, with their sources")
    ap.add_argument("--results", type=Path, help="the replays the sample came from")
    ap.add_argument("--out", type=Path, help="default: agreement.md next to the key")
    args = ap.parse_args(argv)
    with args.key.open(newline="", encoding="utf-8") as f:
        key = list(csv.DictReader(f))
    raters = {}
    if args.human:
        human = load_labels(args.human)
        if args.human_kind:
            kinds = {r["item"]: _kind(r) for r in key}
            human = {k: v for k, v in human.items() if kinds.get(k) == args.human_kind}
        raters["Human rater"] = human
    if args.agent:
        agent: dict[str, str] = {}
        for path in args.agent:
            agent.update(load_labels(path))
        raters["Agent rater"] = agent
    if not raters:
        raise SystemExit("give --human and/or --agent")
    text = report(key, raters)
    if args.adjudicated:
        final = load_labels(args.adjudicated)
        raw = json.loads(args.adjudicated.read_text(encoding="utf-8"))
        sources = Counter(str(v.get("source", "unknown")) for v in raw.values())
        text += "\n" + report(key, {"Adjudicated": final}, header=False)
        text += "\nSources of the adjudicated verdicts:\n\n"
        text += "\n".join(f"- {n}: {src}" for src, n in sources.most_common()) + "\n"
        if args.results:
            text += "\n" + "\n".join(truth_agreement(key, final, args.results))
            text += "\n" + "\n".join(corrected_hidden(key, final, args.results))
    out = args.out or args.key.parent / "agreement.md"
    out.write_text(text.rstrip("\n") + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
