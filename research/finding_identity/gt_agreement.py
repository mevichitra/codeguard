"""Score the manual ground-truth check: how often the harness's truth holds, per rater,
and how well two raters agree.

``python -m research.finding_identity.gt_agreement --human <labels> --agent <labels>``
reads the key (``sample.csv`` from :mod:`gt_sample`) and each rater's labels, keyed by
the blinded item id, and writes ``agreement.md`` next to the key.

Labels: a JSON object ``{item: {"verdict": ...}}``, or a directory of ``<item>.json``
files (as the labelling page's store exports them). A ``pair`` verdict of ``same`` and an
``introduced`` verdict of ``new`` confirm the harness's truth; ``different`` and
``existed`` contradict it; ``unclear`` counts for neither.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from collections.abc import Mapping, Sequence
from pathlib import Path

from .stats import wilson

HERE = Path(__file__).parent
KEY = HERE / "paper" / "ground_truth_check" / "sample.csv"

CONFIRMS = {"same", "new"}
CONTRADICTS = {"different", "existed"}


def load_labels(path: Path) -> dict[str, str]:
    """``{item: verdict}`` from a JSON file or a directory of per-item JSON files."""
    if path.is_dir():
        out = {}
        for f in sorted(path.rglob("*.json")):
            body = json.loads(f.read_text(encoding="utf-8"))
            body = body.get("data", body) if isinstance(body, dict) else {}
            if isinstance(body, dict) and isinstance(body.get("verdict"), str):
                out[f.stem] = body["verdict"]
        return out
    raw = json.loads(path.read_text(encoding="utf-8"))
    return {k: v["verdict"] for k, v in raw.items() if isinstance(v, dict) and "verdict" in v}


def judgement(verdict: str | None) -> str:
    """``confirms``, ``contradicts`` or ``unclear`` (also for a missing label)."""
    if verdict in CONFIRMS:
        return "confirms"
    if verdict in CONTRADICTS:
        return "contradicts"
    return "unclear"


def cohen_kappa(a: Sequence[str], b: Sequence[str]) -> float | None:
    """Cohen's kappa for two equally long label sequences; ``None`` if undefined."""
    n = len(a)
    if n == 0 or n != len(b):
        return None
    observed = sum(x == y for x, y in zip(a, b, strict=True)) / n
    ca, cb = Counter(a), Counter(b)
    expected = sum(ca[k] * cb[k] for k in ca.keys() | cb.keys()) / (n * n)
    if expected == 1:
        return None
    return (observed - expected) / (1 - expected)


def precision_rows(
    key: Sequence[Mapping[str, str]], labels: Mapping[str, str], group: str
) -> list[tuple[str, int, int, int]]:
    """Per value of *group* (and overall): (name, confirms, contradicts, unclear)."""
    groups: dict[str, Counter[str]] = {}
    for row in key:
        j = judgement(labels.get(row["item"]))
        for name in (row[group], "all"):
            groups.setdefault(name, Counter())[j] += 1
    names = [*sorted(n for n in groups if n != "all"), "all"]
    return [
        (n, groups[n]["confirms"], groups[n]["contradicts"], groups[n]["unclear"]) for n in names
    ]


def _kind(row: Mapping[str, str]) -> str:
    return "introduced" if row["truth"] == "new" else "pair"


def report(key: Sequence[Mapping[str, str]], raters: Mapping[str, Mapping[str, str]]) -> str:
    rows = [{**r, "kind": _kind(r)} for r in key]
    out = [
        "# Ground-truth check: results",
        "",
        "Generated by `research/finding_identity/gt_agreement.py`. *Holds* is the share of",
        "decided items (unclear left out) where the rater confirms the harness's truth, with",
        "a Wilson 95% interval.",
        "",
    ]
    for name, labels in raters.items():
        labelled = sum(1 for r in rows if r["item"] in labels)
        out += [f"## {name}", "", f"{labelled} of {len(rows)} items labelled.", ""]
        for group in ("kind", "stratum"):
            out += [
                f"| {group} | confirms | contradicts | unclear | holds | 95% CI |",
                "|---|---:|---:|---:|---:|---|",
            ]
            for g, yes, no, unclear in precision_rows(rows, labels, group):
                ci = wilson(yes, yes + no)
                rate = f"{100 * yes / (yes + no):.1f}%" if yes + no else "n/a"
                cis = f"[{100 * ci[0]:.1f}, {100 * ci[1]:.1f}]" if ci else "n/a"
                out.append(f"| {g} | {yes} | {no} | {unclear} | {rate} | {cis} |")
            out.append("")
    names = list(raters)
    if len(names) == 2:
        both = [r for r in rows if r["item"] in raters[names[0]] and r["item"] in raters[names[1]]]
        a = [judgement(raters[names[0]][r["item"]]) for r in both]
        b = [judgement(raters[names[1]][r["item"]]) for r in both]
        kappa = cohen_kappa(a, b)
        agree = sum(x == y for x, y in zip(a, b, strict=True))
        out += [
            f"## Agreement between {names[0]} and {names[1]}",
            "",
            f"On the {len(both)} items both labelled (confirms / contradicts / unclear):",
            f"{agree} agree ({100 * agree / len(both):.1f}%), Cohen's kappa "
            + (f"{kappa:.2f}." if kappa is not None else "undefined.")
            if both
            else "No item is labelled by both.",
            "",
        ]
        disputed = [r["item"] for r, x, y in zip(both, a, b, strict=True) if x != y]
        if disputed:
            out += ["Items to adjudicate: " + ", ".join(disputed) + ".", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="python -m research.finding_identity.gt_agreement")
    ap.add_argument("--key", type=Path, default=KEY, help="sample.csv from gt_sample")
    ap.add_argument("--human", type=Path, help="the person's labels (file or directory)")
    ap.add_argument("--agent", type=Path, help="the agent rater's labels (file or directory)")
    ap.add_argument("--out", type=Path, help="default: agreement.md next to the key")
    args = ap.parse_args(argv)
    with args.key.open(newline="", encoding="utf-8") as f:
        key = list(csv.DictReader(f))
    raters = {}
    if args.human:
        raters["Human rater"] = load_labels(args.human)
    if args.agent:
        raters["Agent rater"] = load_labels(args.agent)
    if not raters:
        raise SystemExit("give --human and/or --agent")
    out = args.out or args.key.parent / "agreement.md"
    out.write_text(report(key, raters) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
